// Consolidate the modular Next CSS (globals-core.css + tokens/*.css) into ONE
// port-ready Tailwind v4 source for the no-build Liquid theme.
// Reads globals-core.css (production layer) — NOT globals.css — so the prototype-only
// data-preset style switcher in tokens/presets.css never leaks into the Shopify theme.
// Source of truth stays the modular files; this just inlines the local @imports.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");          // web/
// Strip the Google-Fonts @import — the Liquid theme loads fonts via Shopify `| font_face`
// (Shopify-hosted, no external CDN → Theme-Store compliant). The prototype keeps it.
const globals = readFileSync(resolve(ROOT, "app/globals-core.css"), "utf8")
  .replace(/@import\s+url\(['"]?https:\/\/fonts\.googleapis\.com[^)]*\)\s*;\s*/g, "/* fonts: loaded by theme.liquid via Shopify font_face */\n");

// Replace every `@import "../tokens/X.css" [layer(base)];` with the file's contents.
const out = globals.replace(
  /@import\s+"(\.\.\/tokens\/[^"]+)"(\s+layer\(([^)]+)\))?\s*;/g,
  (_m, rel, _layerKw, layer) => {
    const css = readFileSync(resolve(ROOT, "app", rel), "utf8").trim();
    const body = layer ? `@layer ${layer} {\n${css}\n}` : css;
    return `/* ---- inlined ${rel} ---- */\n${body}`;
  },
);

const dest = resolve(ROOT, "theme/assets/tailwind.css");
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, `/* GENERATED by web/scripts/build-theme-css.mjs — edit app/globals.css + tokens/*.css, then regenerate. */\n${out}`);
console.log(`wrote ${dest} (${out.length} bytes)`);
